import { QueryClient, QueryClientProvider } from '@tanstack/react-query'
import { render, screen, waitFor } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { beforeEach, describe, expect, it, vi } from 'vitest'
import { api } from '../../lib/api'
import { UtilityConfigurationModal } from './UtilityConfigurationModal'
import type { UtilityContract } from '../../contracts/utilities'

vi.mock('../../lib/session', () => ({ useSession: () => ({ token: 'session' }) }))
const contract: UtilityContract = { id: 'contract', property_id: 'home', key: 'power-contract', label: 'Power', tracking_mode: 'meter', unit: 'kWh', start_date: '2026-01-01', end_date: null, retired: false, sort_order: 0 }
const second: UtilityContract = { ...contract, id: 'second', key: 'water-contract', label: 'Water', sort_order: 1 }
function setup(property = true) {
  const client = new QueryClient({ defaultOptions: { queries: { retry: false } } })
  render(<QueryClientProvider client={client}><UtilityConfigurationModal subject={property ? { type: 'property', id: 'home' } : null} subjectName="Home" onClose={vi.fn()} /></QueryClientProvider>)
  return userEvent.setup()
}
const openOptions = async (user: ReturnType<typeof userEvent.setup>) => {
  await user.click(screen.getByRole('button', { name: 'Utility contracts options' }))
}
beforeEach(() => {
  vi.restoreAllMocks()
  vi.spyOn(api, 'listUtilityContracts').mockResolvedValue([contract])
  vi.spyOn(api, 'listUtilityContractPrices').mockResolvedValue([{ id: 'price', effective_on: '2026-01-01', price: 0.15 }])
})
describe('UtilityConfigurationModal', () => {
  it('requires a property and never offers global utility types', () => {
    setup(false)
    expect(screen.getByText('Select a property to manage its utility contracts.')).toBeInTheDocument()
    expect(screen.queryByRole('button', { name: 'Utility contracts options' })).not.toBeInTheDocument()
    expect(screen.queryByRole('menuitem', { name: 'New utility contract' })).not.toBeInTheDocument()
    expect(api.listUtilityContracts).not.toHaveBeenCalled()
  })
  it('edits dates and tracking without allowing property reassignment', async () => {
    const update = vi.spyOn(api, 'updateUtilityContract').mockResolvedValue(contract)
    const user = setup()
    await user.click(await screen.findByRole('button', { name: /Power/ }))
    expect(screen.queryByText(/This contract permanently belongs/)).not.toBeInTheDocument()
    await user.clear(screen.getByLabelText('Name'))
    await user.type(screen.getByLabelText('Name'), 'Electricity')
    await user.selectOptions(screen.getByLabelText('Tracking'), 'usage')
    await user.click(screen.getByRole('button', { name: 'Save contract' }))
    await waitFor(() => expect(update).toHaveBeenCalledWith('session', 'contract', { color: '#1e6fd6', label: 'Electricity', tracking_mode: 'usage', unit: 'kWh', start_date: '2026-01-01', end_date: null }))
    expect(screen.queryByLabelText('Property')).not.toBeInTheDocument()
  })
  it('preserves a saved custom hex and selects a concrete swatch without submitting', async () => {
    vi.mocked(api.listUtilityContracts).mockResolvedValue([{ ...contract, color: '#123456' }])
    const update = vi.spyOn(api, 'updateUtilityContract').mockImplementation(async (_token, _id, config) => ({ ...contract, ...config }))
    const user = setup()
    await user.click(await screen.findByRole('button', { name: /Power/ }))
    const trigger = screen.getByRole('button', { name: 'Contract color' })
    expect(trigger).toHaveStyle({ background: '#123456' })
    expect(screen.queryByRole('button', { name: /Automatic|Reset/ })).not.toBeInTheDocument()
    await user.click(trigger)
    expect(screen.getByRole('menu', { name: 'Contract colors' })).toBeInTheDocument()
    expect(screen.getByRole('menuitemradio', { name: 'Custom (#123456)' })).toHaveAttribute('aria-checked', 'true')
    expect(update).not.toHaveBeenCalled()
    await user.keyboard('{Escape}')
    await user.click(screen.getByRole('button', { name: 'Save contract' }))
    await waitFor(() => expect(update).toHaveBeenLastCalledWith('session', 'contract', expect.objectContaining({ color: '#123456' })))
    await user.click(trigger)
    await user.click(screen.getByRole('menuitemradio', { name: 'Green (#12946f)' }))
    expect(trigger).toHaveFocus()
    expect(trigger).toHaveStyle({ background: '#12946f' })
    expect(trigger).toHaveAttribute('aria-expanded', 'false')
    expect(screen.queryByRole('menu')).not.toBeInTheDocument()
    expect(update).toHaveBeenCalledTimes(1)
    await user.click(screen.getByRole('button', { name: 'Save contract' }))
    await waitFor(() => expect(update).toHaveBeenLastCalledWith('session', 'contract', expect.objectContaining({ color: '#12946f' })))
  })
  it('supports keyboard navigation, selection, Escape and Tab without submitting or closing the sheet', async () => {
    const update = vi.spyOn(api, 'updateUtilityContract')
    const user = setup()
    await user.click(await screen.findByRole('button', { name: /Power/ }))
    const trigger = screen.getByRole('button', { name: 'Contract color' })
    trigger.focus()
    await user.keyboard('{ArrowDown}')
    expect(screen.getByRole('menuitemradio', { name: 'Blue (#1e6fd6)' })).toHaveFocus()
    await user.keyboard('{ArrowRight}')
    expect(screen.getByRole('menuitemradio', { name: 'Red (#c43f3f)' })).toHaveFocus()
    await user.keyboard('{End}')
    expect(screen.getByRole('menuitemradio', { name: 'Ink (#111827)' })).toHaveFocus()
    await user.keyboard('{ArrowDown}')
    expect(screen.getByRole('menuitemradio', { name: 'Blue (#1e6fd6)' })).toHaveFocus()
    await user.keyboard('{ArrowUp}{Home}{ArrowLeft}')
    expect(screen.getByRole('menuitemradio', { name: 'Ink (#111827)' })).toHaveFocus()
    await user.keyboard('{Enter}')
    expect(trigger).toHaveFocus()
    expect(trigger).toHaveStyle({ background: '#111827' })
    await user.keyboard(' ')
    expect(screen.getByRole('menuitemradio', { name: 'Ink (#111827)' })).toHaveFocus()
    await user.keyboard('{Escape}')
    expect(trigger).toHaveFocus()
    expect(screen.getByRole('dialog')).toBeInTheDocument()
    expect(screen.queryByRole('menu')).not.toBeInTheDocument()
    await user.keyboard('{ArrowUp}{Tab}')
    expect(screen.getByLabelText('Tracking')).toHaveFocus()
    expect(screen.queryByRole('menu')).not.toBeInTheDocument()
    expect(update).not.toHaveBeenCalled()
  })
  it('resolves a legacy null color once from its original label and dismisses on outside interaction', async () => {
    vi.mocked(api.listUtilityContracts).mockResolvedValue([{ ...contract, label: 'Electricity', color: null }])
    const update = vi.spyOn(api, 'updateUtilityContract').mockResolvedValue(contract)
    const user = setup()
    await user.click(await screen.findByRole('button', { name: /Electricity/ }))
    const trigger = screen.getByRole('button', { name: 'Contract color' })
    expect(trigger).toHaveStyle({ background: '#eab308' })
    await user.click(trigger)
    await user.click(screen.getByLabelText('Name'))
    expect(screen.queryByRole('menu')).not.toBeInTheDocument()
    await user.clear(screen.getByLabelText('Name'))
    await user.type(screen.getByLabelText('Name'), 'Water')
    expect(trigger).toHaveStyle({ background: '#eab308' })
    await user.click(screen.getByRole('button', { name: 'Save contract' }))
    await waitFor(() => expect(update).toHaveBeenCalledWith('session', 'contract', expect.objectContaining({ label: 'Water', color: '#eab308' })))
  })
  it('edits existing month-effective price history rather than appending an audit configuration', async () => {
    const update = vi.spyOn(api, 'updateUtilityContractPrice').mockResolvedValue({ id: 'price', effective_on: '2026-01-01', price: 0.2 })
    const user = setup()
    await user.click(await screen.findByRole('button', { name: /Power/ }))
    expect(screen.queryByText(/Prices apply to the whole effective month/)).not.toBeInTheDocument()
    await user.click(await screen.findByRole('button', { name: /Effective from 2026-01/ }))
    await user.clear(screen.getByLabelText('Unit price'))
    await user.type(screen.getByLabelText('Unit price'), '0.2')
    await user.click(screen.getByRole('button', { name: 'Save price' }))
    await waitFor(() => expect(update).toHaveBeenCalledWith('session', 'contract', 'price', { effective_on: '2026-01-01', price: 0.2 }))
  })
  it('validates price precision and leaves actual bills untouched by the UI', async () => {
    const create = vi.spyOn(api, 'createUtilityContractPrice')
    const user = setup()
    await user.click(await screen.findByRole('button', { name: /Power/ }))
    await user.type(screen.getByLabelText('Unit price'), '0.1234567')
    await user.click(screen.getByRole('button', { name: 'Add price' }))
    expect(await screen.findByRole('alert')).toHaveTextContent('at most six decimal places')
    expect(create).not.toHaveBeenCalled()
  })
  it('creates a contract belonging to the selected property from the options menu', async () => {
    const create = vi.spyOn(api, 'createUtilityContract').mockResolvedValue(contract)
    const user = setup()
    await user.click(await screen.findByRole('button', { name: 'Utility contracts options' }))
    await user.click(screen.getByRole('menuitem', { name: 'New utility contract' }))
    expect(screen.getByRole('button', { name: 'Contract color' })).toHaveStyle({ background: '#1e6fd6' })
    await user.click(screen.getByRole('button', { name: 'Contract color' }))
    await user.click(screen.getByRole('menuitemradio', { name: 'Slate (#64748b)' }))
    expect(create).not.toHaveBeenCalled()
    await user.type(screen.getByLabelText('Name'), 'Rent')
    await user.selectOptions(screen.getByLabelText('Tracking'), 'fixed')
    await user.clear(screen.getByLabelText('Start date'))
    await user.type(screen.getByLabelText('Start date'), '2026-01-01')
    await user.type(screen.getByLabelText('Initial monthly price'), '1500')
    await user.click(screen.getByRole('button', { name: 'Save contract' }))
    await waitFor(() => expect(create).toHaveBeenCalledWith('session', { color: '#64748b', property_id: 'home', label: 'Rent', tracking_mode: 'fixed', unit: '', start_date: '2026-01-01', end_date: null, initial_price: 1500 }))
  })
  it('hides retired contracts through the options menu toggle', async () => {
    vi.spyOn(api, 'listUtilityContracts').mockResolvedValue([
      contract,
      { ...second, end_date: '2026-06-30', retired: true },
    ])
    const user = setup()
    expect(await screen.findByRole('button', { name: /Water/ })).toBeInTheDocument()
    await openOptions(user)
    await user.click(screen.getByRole('menuitemcheckbox', { name: 'Show retired contracts' }))
    expect(screen.queryByRole('button', { name: /Water/ })).not.toBeInTheDocument()
    expect(screen.getByRole('button', { name: /Power/ })).toBeInTheDocument()
  })
  it('reorders contracts with chevrons and sends the complete order', async () => {
    vi.spyOn(api, 'listUtilityContracts').mockResolvedValue([contract, second])
    const reorder = vi.spyOn(api, 'reorderUtilityContracts').mockResolvedValue([second, contract])
    const user = setup()
    await openOptions(user)
    await user.click(screen.getByRole('menuitem', { name: 'Reorder contracts' }))
    expect(screen.getByRole('button', { name: 'Move Power up' })).toBeDisabled()
    expect(screen.getByRole('button', { name: 'Move Water down' })).toBeDisabled()
    await user.click(screen.getByRole('button', { name: 'Move Water up' }))
    await waitFor(() => expect(reorder).toHaveBeenCalledWith('session', 'home', ['second', 'contract']))
    await openOptions(user)
    await user.click(screen.getByRole('menuitem', { name: 'Done reordering' }))
    expect(screen.queryByRole('button', { name: 'Move Water up' })).not.toBeInTheDocument()
    expect(screen.getByRole('button', { name: /Power/ })).toBeInTheDocument()
  })
  it('reverts to the server order when a move fails', async () => {
    vi.spyOn(api, 'listUtilityContracts').mockResolvedValue([contract, second])
    vi.spyOn(api, 'reorderUtilityContracts').mockRejectedValue(new Error('Network down'))
    const user = setup()
    await openOptions(user)
    await user.click(screen.getByRole('menuitem', { name: 'Reorder contracts' }))
    await user.click(screen.getByRole('button', { name: 'Move Water up' }))
    expect(await screen.findByRole('alert')).toHaveTextContent('Network down')
    await openOptions(user)
    await user.click(screen.getByRole('menuitem', { name: 'Done reordering' }))
    const labels = screen.getAllByRole('button', { name: /Power|Water/ }).map((node) => node.textContent)
    expect(labels[0]).toContain('Power')
  })
})
